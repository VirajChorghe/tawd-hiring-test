/** Fixed format so the log reads the same for everyone, wherever they are: Pacific time, said as "PT" (0.96.0), e.g. "Oct 7, 2026, 3:20 PM PT". */
export function formatWhen(value: Date): string {
  return `${new Intl.DateTimeFormat("en-US", {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "America/Los_Angeles",
  }).format(value)} PT`;
}
