/** The chips under a project's name, the same on every project screen. */
export function projectChips(project: {
  trade: Trade;
  tier: Tier;
  lane: Lane;
  laneOption: LaneOption | null;
  conceptCount: number | null;
  conceptsBuilt?: number | null;
}): string[] {
  return [
    tradeLabels[project.trade],
    `${tierLabels[project.tier].split(" (")[0]} tier`,
    project.laneOption
      ? laneOptionLabels[project.laneOption]
      : laneLabels[project.lane].replace(" - ", ": "),
    project.conceptsBuilt != null
      ? `${project.conceptsBuilt} concept${project.conceptsBuilt === 1 ? "" : "s"} built`
      : project.conceptCount === null
        ? "No concepts"
        : `${project.conceptCount} concept${project.conceptCount === 1 ? "" : "s"}`,
  ];
}

